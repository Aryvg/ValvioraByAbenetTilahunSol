async function getAuthToken() {
    try {
        const response = await fetch('https://valviorabackend2.onrender.com/refresh', { credentials: 'include' });
        if (!response.ok) return null;
        const data = await response.json();
        return data?.accessToken || null;
    } catch (error) {
        console.warn('Refresh failed:', error);
        return null;
    }
}

async function toggleSubscribe(button, videoId, token) {
    if (!button || !videoId || !token) return;

    const isSubscribed = button.dataset.subscribed === 'true';
    const nextDelta = isSubscribed ? -1 : 1;

    button.disabled = true;
    try {
        const response = await fetch(`https://valviorabackend2.onrender.com/videoSummaryApi/${encodeURIComponent(videoId)}`, {
            method: 'PUT',
            credentials: 'include',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${token}`
            },
            body: JSON.stringify({ subscribeDelta: nextDelta })
        });

        if (!response.ok) throw new Error(`subscribe update failed (${response.status})`);

        button.dataset.subscribed = String(!isSubscribed);
        button.textContent = !isSubscribed ? 'Subscribed' : 'Subscribe';
    } catch (error) {
        console.error('toggleSubscribe failed:', error);
    } finally {
        button.disabled = false;
    }
}

export function renderVideoById(id) {
    const video = videos.find(v => v.id === id) || videos[0];
    if (!video) return;

    const videoContainer = `
        <video class="main-video"
                src="${video.src}" controls autoplay playsinline
                width="1000"></video>
            <div class="video-title">${video.videoTitle}</div>
            <div class="vid-bottom">
                <div class="wider-vid-container">
                    <div class="channel-profile">
                        <img class="vid-image" src="${video.channelProfile}"/>
                    </div>
                    <div class="na">
                        <div class="vid-channel-name">${video.channelName}</div>
                        <div class="vid-view">${video.views}</div>
                    </div>
                    <div class="subscribe-button">
                        <button class="subscribe">Subscribe</button>
                    </div>
                </div>
                <div class="right-vid">
                    <button class="like-button" aria-pressed="false" title="Like">Like</button>
                    <button class="dislike-button" aria-pressed="false" title="Dislike">Dislike</button>
                    <div class="share-button" role="button" title="Share">share</div>
                    <div class="download-button" role="button" title="Download">Download</div>
                     <div class="three-dot-button" role="button" title="More"></div>
                </div>
            </div>
            <div class="description-section">
                <div class="description-title">266k views 3 years ago</div>
                <div class="description-text">
                    <div class="video-explanation">${video.videoExplanation}</div>
                    <div class="video-description" style="display:none">${video.videoDescription}</div>
                    <button class="show-more-button" aria-expanded="false">...more</button>
                </div>

            </div> 
            <div class="comment-section">
                <div class="comment-description">
                    <div class="how-much">0 Comments</div>
                    <div>
                        <div class="sort">Sort by</div>
                    </div>
                </div>
                <div class="comment-input">
                    <div class="comment-profile-picture">
                        <img src="images/images (2).jpeg" class="comment-image" />
                    </div>
                    <input class="comment-box js-comment-box" placeholder="Add a comment" />
                </div>
                <div class="comments">
                    <!-- comments will be rendered here from localStorage -->
                </div>
            </div>
    `;

    document.querySelector('.video-container').innerHTML = videoContainer;

    const subscribeBtn = document.querySelector('.video-container .subscribe');
    if (subscribeBtn) {
        subscribeBtn.dataset.subscribed = 'false';
        subscribeBtn.addEventListener('click', async () => {
            const token = await getAuthToken();
            if (!token) {
                console.warn('No auth token available for subscribe toggle.');
                return;
            }
            await toggleSubscribe(subscribeBtn, video.id, token);
        });
    }

    // Attempt to autoplay the inserted video (muted to satisfy browser autoplay policies)
    const mainVideoEl = document.querySelector('.video-container .main-video');
    if (mainVideoEl) {
        // Ensure the video is unmuted so audio plays by default
        mainVideoEl.muted = false;
        const playPromise = mainVideoEl.play();
        if (playPromise && playPromise.catch) {
            playPromise.catch((err) => {
                // Autoplay may be blocked by browser autoplay policy; leave it paused so user can start it manually
                console.warn('Autoplay blocked or failed:', err);
            });
        }

        // Add event listener for when video ends to play next video
        mainVideoEl.addEventListener('ended', () => {
            // Find the next sidebar video that is not hidden and has a corresponding video
            const sidebarImages = document.querySelectorAll('.side-image');
            for (const img of sidebarImages) {
                const container = img.closest('.sidebar-item-container');
                if (container && !container.classList.contains('hidden-by-video')) {
                    const id = img.dataset.id;
                    if (id && videos.some(v => v.id === id)) {
                        // Simulate click to open next video
                        img.click();
                        break;
                    }
                }
            }
        });
    }
}

// If this module is loaded on the second page, check URL param and render appropriate video
if (document.querySelector('.video-container')) {
    const params = new URLSearchParams(window.location.search);
    const id = params.get('id');
    if (id) {
        if (videos.some(v => v.id === id)) {
            renderVideoById(id);
        } else {
            document.querySelector('.video-container').innerHTML = '<div class="video-not-found">Sorry, this video was not found.</div>';
        }
    } else {
        // default to first video
        renderVideoById(videos[0].id);
    }
}
