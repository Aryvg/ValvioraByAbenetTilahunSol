export const setupSidebarPopupTriggers = () => {
    if (document.documentElement.dataset.sidebarPopupTriggersReady === 'true') {
        return;
    }

    document.documentElement.dataset.sidebarPopupTriggersReady = 'true';

    const attachTriggerHandlers = () => {
        document.querySelectorAll('.js-contact-trigger').forEach((button) => {
            button.onclick = (event) => {
                event.preventDefault();
                event.stopPropagation();
                closeSupportPopup();
                closeAboutPopup();
                closeFaqPopup();
                closeTermsPopup();
                openContactPopup();
            };
        });

        document.querySelectorAll('.js-support-trigger').forEach((button) => {
            button.onclick = (event) => {
                event.preventDefault();
                event.stopPropagation();
                closeContactPopup();
                closeAboutPopup();
                closeFaqPopup();
                closeTermsPopup();
                openSupportPopup();
            };
        });

        document.querySelectorAll('.js-about-trigger').forEach((button) => {
            button.onclick = (event) => {
                event.preventDefault();
                event.stopPropagation();
                closeContactPopup();
                closeSupportPopup();
                closeFaqPopup();
                closeTermsPopup();
                openAboutPopup();
            };
        });

        document.querySelectorAll('.js-faq-trigger').forEach((button) => {
            button.onclick = (event) => {
                event.preventDefault();
                event.stopPropagation();
                closeContactPopup();
                closeSupportPopup();
                closeAboutPopup();
                closeTermsPopup();
                openFaqPopup();
            };
        });

        document.querySelectorAll('.js-terms-trigger').forEach((button) => {
            button.onclick = (event) => {
                event.preventDefault();
                event.stopPropagation();
                closeContactPopup();
                closeSupportPopup();
                closeAboutPopup();
                closeFaqPopup();
                openTermsPopup();
            };
        });
    };

    attachTriggerHandlers();

    document.addEventListener('click', (event) => {
        const trigger = event.target.closest('.js-contact-trigger');
        if (trigger) {
            event.preventDefault();
            event.stopPropagation();
            closeSupportPopup();
            closeAboutPopup();
            closeFaqPopup();
            closeTermsPopup();
            openContactPopup();
            return;
        }

        const supportTrigger = event.target.closest('.js-support-trigger');
        if (supportTrigger) {
            event.preventDefault();
            event.stopPropagation();
            closeContactPopup();
            closeAboutPopup();
            closeFaqPopup();
            closeTermsPopup();
            openSupportPopup();
            return;
        }

        const aboutTrigger = event.target.closest('.js-about-trigger');
        if (aboutTrigger) {
            event.preventDefault();
            event.stopPropagation();
            closeContactPopup();
            closeSupportPopup();
            closeFaqPopup();
            closeTermsPopup();
            openAboutPopup();
            return;
        }

        const faqTrigger = event.target.closest('.js-faq-trigger');
        if (faqTrigger) {
            event.preventDefault();
            event.stopPropagation();
            closeContactPopup();
            closeSupportPopup();
            closeAboutPopup();
            closeTermsPopup();
            openFaqPopup();
            return;
        }

        const termsTrigger = event.target.closest('.js-terms-trigger');
        if (termsTrigger) {
            event.preventDefault();
            event.stopPropagation();
            closeContactPopup();
            closeSupportPopup();
            closeAboutPopup();
            closeFaqPopup();
            openTermsPopup();
            return;
        }

        if (event.target.closest('.js-contact-popup-close')) {
            event.preventDefault();
            event.stopPropagation();
            closeContactPopup();
            return;
        }

        if (event.target.closest('.js-support-popup-close')) {
            event.preventDefault();
            event.stopPropagation();
            closeSupportPopup();
            return;
        }

        if (event.target.closest('.js-about-popup-close')) {
            event.preventDefault();
            event.stopPropagation();
            closeAboutPopup();
            return;
        }

        if (event.target.closest('.js-faq-popup-close')) {
            event.preventDefault();
            event.stopPropagation();
            closeFaqPopup();
            return;
        }

        if (event.target.closest('.js-terms-popup-close')) {
            event.preventDefault();
            event.stopPropagation();
            closeTermsPopup();
        }
    }, true);

    document.addEventListener('click', (event) => {
        const popup = getPopupById(contactPopupId);
        if (popup && popup.getAttribute('aria-hidden') === 'false' && event.target === popup) {
            closeContactPopup();
        }

        const supportPopup = getPopupById(supportPopupId);
        if (supportPopup && supportPopup.getAttribute('aria-hidden') === 'false' && event.target === supportPopup) {
            closeSupportPopup();
        }

        const aboutPopup = getPopupById(aboutPopupId);
        if (aboutPopup && aboutPopup.getAttribute('aria-hidden') === 'false' && event.target === aboutPopup) {
            closeAboutPopup();
        }

        const faqPopup = getPopupById(faqPopupId);
        if (faqPopup && faqPopup.getAttribute('aria-hidden') === 'false' && event.target === faqPopup) {
            closeFaqPopup();
        }

        const termsPopup = getPopupById(termsPopupId);
        if (termsPopup && termsPopup.getAttribute('aria-hidden') === 'false' && event.target === termsPopup) {
            closeTermsPopup();
        }
    }, true);

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape') {
            closeContactPopup();
            closeSupportPopup();
            closeAboutPopup();
            closeFaqPopup();
            closeTermsPopup();
        }
    });
};

const setupContactPopup = () => {
    if (window.__sharedSidebarContactPopupBound) {
        return;
    }

    window.__sharedSidebarContactPopupBound = true;
    setupSidebarPopupTriggers();
};

